"""Regenerate Plans/Legs/Leg Decisions.md (tables with a sprite per tier row).
Run from the project root: python tools/leg_notes.py
Stats come from data/items_raw.json (Legacy + Reloaded packs) plus the rules written in each section's text."""
import json

BS = chr(92)
raw = json.load(open("data/items_raw.json", encoding="utf-8"))
raw = raw if isinstance(raw, list) else raw["items"]
by = {i["id"]: i for i in raw}
tiers = lambda id: by[id]["stats"]["reloaded"]["tiers"]


def rb(id, tier):
    v = tiers(id)[tier]
    return dict(v["base"]), dict(v.get("max") or v["base"])


DMG = ("phyDmg", "expDmg", "eleDmg")
DRAIN = ("heaDmg", "eneDmg", "phyResDmg", "expResDmg", "eleResDmg")


def scale(b, m, mult):
    """Boost HP, stomp damage and drains; walk / jump / push / range / weight / resistances stay."""
    b, m = dict(b), dict(m)
    for x in (b, m):
        if "health" in x:
            x["health"] = round(x["health"] * mult)
        for k in DMG:
            if k in x:
                x[k] = [round(x[k][0] * mult), round(x[k][1] * mult)]
        for k in DRAIN:
            if k in x:
                x[k] = round(x[k] * mult)
    return b, m


def to_heat(b, m):  # energy stomp -> heat stomp: eleDmg -> expDmg, energy drain x0.75 -> heat drain
    b, m = dict(b), dict(m)
    for x in (b, m):
        x["expDmg"] = x.pop("eleDmg")
        x["heaDmg"] = round(x.pop("eneDmg") * .75)
    return b, m


def to_phys(b, m):  # energy stomp -> physical: eleDmg x1.25 -> phyDmg, no drain
    b, m = dict(b), dict(m)
    for x in (b, m):
        a = x.pop("eleDmg")
        x["phyDmg"] = [round(a[0] * 1.25), round(a[1] * 1.25)]
        x.pop("eneDmg")
    return b, m


def rng(v):
    return f"{v[0]}→{v[1]}" if v[0] != v[1] else f"{v[0]}"


def cell(b, m, k):
    a, z = b.get(k), m.get(k, b.get(k))
    if a is None:
        return "–"
    return f"{a}→{z}" if a != z else f"{a}"


def stomp(b, m):
    for k, l in (("phyDmg", "phy"), ("expDmg", "exp"), ("eleDmg", "ele")):
        if k in b:
            lo = f"{b[k][0]}-{b[k][1]}"
            hi = f"{m[k][0]}-{m[k][1]}"
            return (f"{lo}→{hi}" if lo != hi else lo) + f" {l}"
    return "–"


def drain(b, m):
    o = []
    for k, l in (("heaDmg", "heat"), ("eneDmg", "energy"), ("phyResDmg", "phy res"), ("expResDmg", "exp res"), ("eleResDmg", "ele res")):
        if k in b:
            o.append(f"{l} {cell(b, m, k)}")
    return ", ".join(o) or "–"


def img(sprite, w=72):
    return f"![[Legs/sprites/{sprite}.png{BS}|{w}]]"


def table(rows):
    o = ["| Tier | Look | HP | Stomp | Drain | Res | Walk / jump | Push | Range | Weight |", "|---|---|---|---|---|---|---|---|---|---|"]
    for lab, sp, b, m in rows:
        res = "/".join(str(b.get(k, 0)) for k in ("phyRes", "expRes", "eleRes"))
        res = "–" if res == "0/0/0" else res
        o.append(f"| {lab} | {img(sp)} | {cell(b,m,'health')} | {stomp(b,m)} | {drain(b,m)} | {res} | {b.get('walk','–')} / {b.get('jump','–')} | {b.get('push','–')} | {b['range'][0] if 'range' in b else '–'} | {b['weight']} |")
    return "\n".join(o)


def block(title, rows, note=""):
    return f"#### {title}\n" + (note + "\n\n" if note else "\n") + table(rows) + "\n"


