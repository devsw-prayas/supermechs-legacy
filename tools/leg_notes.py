def from_phys(b, m, mode):
    b, m = dict(b), dict(m)
    for x in (b, m):
        a = x.pop("phyDmg")
        lo, hi = round(a[0] / 1.25), round(a[1] / 1.25)
        avg = (lo + hi) / 2
        if mode == "h":
            x["expDmg"] = [lo, hi]
            x["heaDmg"] = round(avg * .23)
        else:
            x["eleDmg"] = [lo, hi]
            x["eneDmg"] = round(avg * .31)
    return b, m


